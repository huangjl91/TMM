import type { ReactNode } from 'react'

const TERMS = [
  ['预测目标', '你希望提前知道的那个数值。', '例如预测明天客流，目标是“人数”，日期用来说明预测哪一天。', '对应下方的“预测目标”和“目标单位”，不要把编号当成要预测的数值。'],
  ['模型与基线', '模型是从已知信息得到估计的一套规则；基线是用来比较的简单规则。', '“明天人数先按今天人数估计”就是一个简单基线。它不一定准确，但能帮助判断复杂方法是否值得。', '本实验会将候选方法与“上一期观测值”放在同一测试段比较。'],
  ['训练、验证与测试', '训练用来建立方法，验证用来选择方法，测试用来检查选定方法在留出数据上的表现。', '像练习、挑选解题方法和最后测验；测验答案不能提前用于挑方法。', '本实验按时间留出最后 20% 作测试，方法选择只使用更早的训练段。'],
  ['数据泄漏', '预测时用到了当时还不可能知道的信息，结果会显得过于理想。', '预测周二客流时，如果用了周三的实际客流，就偷看了未来。', '核对每一列在预测那个时刻是否已知；逐期一步预测可以使用当时已经观测到的上一期数据。'],
  ['MAE：平均绝对误差', '把每次“差了多少”取正数，再求平均。数值越小，平均偏差越小。', '教学例子：实际为 10、20 人，预测为 12、16 人，绝对误差为 2、4 人，MAE = (2 + 4) ÷ 2 = 3 人。', '与目标同单位；只能在可比的数据、目标和测试范围内比较。'],
  ['RMSE：均方根误差', '先把误差平方，求平均，再开平方；它对大的误差更敏感。', '同一个例子：RMSE = √((2² + 4²) ÷ 2) = √10 ≈ 3.16 人。', '本实验用训练段验证 RMSE 选择方法，再报告独立测试段误差。'],
  ['MAPE：平均绝对百分比误差', '把每次绝对误差除以实际值的绝对值，再取平均并转成百分比。', '同一个例子：MAPE = (2/10 + 4/20) ÷ 2 × 100% = 20%。', '实际值为零时没有定义，接近零时可能非常大。表中“不适用”不是零误差。'],
  ['残差与预测区间', '残差是实际值与预测值的差；预测区间描述可能的波动范围。', '实际 10 人、预测 12 人，按“实际减预测”定义，残差是 −2 人。误差持续偏向一侧值得检查。', '图中的波动和区间需要结合测试样本量看；本次覆盖率不能保证未来表现。']
] as const

export function PredictionBasics({ stage }: { stage: 'intuition' | 'model_select' | 'experiment' }): ReactNode {
  const questions = stage === 'intuition'
    ? ['要提前知道什么？先找题目要求预测的对象。', '预测哪个时间、地点或范围？不要遗漏题目的限定。', '哪些附件能提供过去的观测？把字段名和来源写进下方回答。']
    : stage === 'model_select'
      ? ['数据是否有时间顺序？先说清一行代表什么。', '最简单能试什么规则？例如沿用上一期观测值。', '准备留出哪些数据检查？如果不如基线，你会怎样调整？']
      : ['先选附件：确认每一行代表一个什么时刻或周期。', '再选时间列和目标列：写明目标单位，检查缺失值和异常值。', '最后写预期：你想比较哪种方法、哪个指标？没有把握可以如实写。']
  return <aside className="prediction-basics" aria-label="预测入门帮助">
    <details open>
      <summary>第一次做预测？先按这三个小问题想一想</summary>
      <ol>{questions.map((question) => <li key={question}>{question}</li>)}</ol>
      <p>把你的想法填入下面对应的输入框。这里提供思考顺序，不会自动替你填写或判定掌握。</p>
    </details>
    <details>
      <summary>术语小词典 · 点击名称，看白话解释和小例子</summary>
      <p>下面数字只用于教学，不是你的附件数据或实验结果。</p>
      {TERMS.map(([name, meaning, example, use]) => <details key={name}>
        <summary>{name}</summary>
        <p><b>是什么意思：</b>{meaning}</p>
        <p><b>小例子：</b>{example}</p>
        <p><b>在这里怎么用：</b>{use}</p>
      </details>)}
    </details>
  </aside>
}
