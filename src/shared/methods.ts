const norm = (s: string): string => s.toLowerCase().replace(/[\s_\-/]/g, '')

/**
 * 无分词库时的取词办法：中文按字符二元组，英文数字按整词。
 * 二元组对短标签容易误命中，所以打分时正文只作弱信号。
 */
export function tokenize(s: string): string[] {
  const out: string[] = []
  for (const run of String(s)
    .toLowerCase()
    .match(/[a-z0-9]+|[一-鿿]+/g) ?? []) {
    if (/^[a-z0-9]+$/.test(run)) {
      if (run.length >= 2) out.push(run)
      continue
    }
    if (run.length === 1) out.push(run)
    else for (let i = 0; i < run.length - 1; i++) out.push(run.slice(i, i + 2))
  }
  return out
}

export function scoreMethod(query: string, m: MethodCard): number {
  const q = norm(query)
  if (!q) return 0
  let score = 0
  if (q.includes(norm(m.name))) score += 10
  for (const a of m.aka) if (a.length >= 2 && q.includes(norm(a))) score += 8
  let tagHits = 0
  let partial = 0
  for (const t of m.tags) {
    const n = norm(t)
    if (n.length < 2) continue
    if (q.includes(n)) tagHits++
    else if (n.includes(q)) partial++
  }
  score += Math.min(tagHits, 3) * 4 + Math.min(partial, 2) * 2
  if (q.includes(m.category)) score += 3
  const qts = new Set(tokenize(query))
  // 卡面文字（适用条件/数据要求/坑/追问/线索）按绝对命中量累加：
  // 短查询基本不加分，喂整段任务卡文本时才会累积起来，所以两条路径各用各的入口。
  const body = new Set(
    tokenize([m.when, m.needs, m.output, m.sensitivity, ...m.pitfalls, ...m.asks, ...m.signals].join(' '))
  )
  let overlap = 0
  for (const t of qts) if (body.has(t)) overlap++
  score += Math.min(8, overlap * 0.8)
  return score
}

export interface SearchOpts {
  stageId?: number
  limit?: number
}

/** 命中门槛：至少要有一次硬命中（名称/别名/标签/类别），光靠卡面文字重叠不算命中 */
const MIN_SCORE = 4.5

/** 整场最常翻的几张：按适用阶段数排序，读题/假设这类还没到选型的阶段用它们垫底 */
export function popularMethods(limit = 6): MethodCard[] {
  return [...METHOD_CARDS]
    .sort((a, b) => b.stages.length - a.stages.length || a.name.localeCompare(b.name, 'zh'))
    .slice(0, limit)
}

/** 搜索框用：短关键词按硬命中排序，查不到就不给结果，不拿不相干的方法凑数 */
export function searchMethods(query: string, opts: SearchOpts = {}): MethodCard[] {
  const limit = opts.limit ?? 6
  const q = String(query ?? '').trim()
  if (!q) {
    if (opts.stageId) {
      const own = methodsForStage(opts.stageId, limit)
      if (own.length) return own
      // 空列表会让人以为方法库是坏的：垫几张通用卡，界面会同时说明这不是本阶段专属
      return popularMethods(limit)
    }
    return [...METHOD_CARDS].sort((a, b) => a.name.localeCompare(b.name, 'zh')).slice(0, limit)
  }
  return METHOD_CARDS.map((m) => ({
    m,
    s: scoreMethod(q, m) + (opts.stageId && m.stages.includes(opts.stageId) ? 3 : 0)
  }))
    .filter((x) => x.s >= MIN_SCORE)
    .sort((a, b) => b.s - a.s || a.m.name.localeCompare(b.m.name, 'zh'))
    .slice(0, limit)
    .map((x) => x.m)
}

/**
 * 提示词注入用：输入是学生那一大段任务卡文本，没有硬命中也要能挑出最贴近的几张卡。
 * 相对门槛（最高分的四成）比绝对分数稳，因为长文本的分数天然更高。
 * 每个类别最多两张：选型阶段要的是「可比较的候选」，全是评价族就等于没得比。
 */
export function topMethodsForText(text: string, stageId?: number, limit = 3): MethodCard[] {
  const q = String(text ?? '').trim()
  if (!q) return stageId ? methodsForStage(stageId, limit) : []
  const ranked = METHOD_CARDS.map((m) => ({
    m,
    s: scoreMethod(q, m) + (stageId && m.stages.includes(stageId) ? 2 : 0)
  })).sort((a, b) => b.s - a.s || a.m.name.localeCompare(b.m.name, 'zh'))
  const best = ranked[0]?.s ?? 0
  if (best < 2) return stageId ? methodsForStage(stageId, limit) : []
  const perCategory = new Map<string, number>()
  const picked: MethodCard[] = []
  for (const x of ranked) {
    if (x.s < best * 0.4) break
    const n = perCategory.get(x.m.category) ?? 0
    if (n >= 2) continue
    perCategory.set(x.m.category, n + 1)
    picked.push(x.m)
    if (picked.length >= limit) break
  }
  return picked
}

export function methodsForStage(stageId: number, limit = 8): MethodCard[] {
  return METHOD_CARDS.filter((m) => m.stages.includes(stageId)).slice(0, limit)
}

/**
 * 喂给 Coach / Executor 的摘要。刻意只给「坑」和「追问」：
 * 这两类内容只能变成问题与检查点，不构成可粘贴正文。
 */
export function digestForPrompt(cards: MethodCard[], max = 3): string {
  const picked = cards.slice(0, max)
  if (!picked.length) return ''
  return [
    '【方法库要点｜只许用来生成追问与检查点，不许把要点念给学生、不许照抄成论文句子】',
    ...picked.map(
      (m) =>
        `- ${m.name}（${m.category}）适用：${m.when}；产出形状：${m.output}\n` +
        `  坑：${m.pitfalls.slice(0, 2).join('；')}\n` +
        `  可追问：${m.asks.slice(0, 2).join(' ')}`
    )
  ].join('\n')
}
